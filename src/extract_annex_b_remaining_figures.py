async def main():
    print(f"Connecting to LightRAG storage at {STORAGE_DIR}...")
    rag = get_rag_instance(working_dir=STORAGE_DIR)
    await rag.initialize_storages()

    texts = [item["content"] for item in ANNEX_B_REMAINING_FIGURE_CHUNKS]
    ids = [item["chunk_id"] for item in ANNEX_B_REMAINING_FIGURE_CHUNKS]

    print(f"Ingesting {len(texts)} Annex B remaining engineering drawing chunks (Figures B8 through B54)...")
    await rag.ainsert(texts, ids=ids)
    print("Ingestion complete! All Annex B engineering figures (B1-B54) are now indexed.")

if __name__ == "__main__":
    asyncio.run(main())
